@Composable
@ReadOnlyComposable
fun t(key: String): String = I18n.get(LocalLang.current, key)

@Composable
@ReadOnlyComposable
fun t(key: String, vararg args: Any?): String = I18n.get(LocalLang.current, key).format(*args)

/**
 * Igual que [t] pero fuera de la composición: para textos que se arman dentro de una corrutina
 * —un snackbar después de una llamada de red—, donde no se puede leer un CompositionLocal.
 * Resuelve contra el idioma guardado en preferencias.
 */
fun t2(key: String, vararg args: Any?): String = I18n.get(uiLang, key).format(*args)

/** Idioma elegido, para los textos que no salen de un composable. Lo fija [Lang] al arrancar. */
@Volatile
var uiLang: Lang = Lang.ES
