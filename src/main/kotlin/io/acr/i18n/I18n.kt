/**
 * Idiomas soportados. Agregar uno es agregar una entrada acá y un mapa en [I18n.tables]:
 * las claves que falten caen al idioma base, así una traducción parcial ya es usable.
 */
enum class Lang(val code: String, val label: String) {
    ES("es", "Español"),
    EN("en", "English"),
    ;

    companion object {
        fun fromCode(code: String?): Lang = entries.firstOrNull { it.code == code } ?: ES
    }
}

val LocalLang = staticCompositionLocalOf { Lang.ES }

