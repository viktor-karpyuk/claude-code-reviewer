    private val tables: Map<Lang, Map<String, String>> = mapOf(Lang.ES to es, Lang.EN to en)

    /** Claves sin traducir en [lang]. Sirve para saber cuánto falta de un idioma nuevo. */
    fun missing(lang: Lang): List<String> {
        val base = tables[Lang.ES].orEmpty().keys
        val target = tables[lang].orEmpty().keys
        return (base - target).sorted()
    }
}

@Composable
@ReadOnlyComposable
fun t(key: String): String = I18n.get(LocalLang.current, key)

@Composable
@ReadOnlyComposable
fun t(key: String, vararg args: Any?): String = I18n.get(LocalLang.current, key).format(*args)
